"""2026-11-12: the kit load check's cost table (the User: "cap voices to fit").

`table.json` beside this file is GENERATED by scripts/gen_load_table.py from the model's measurements
(scripts/dsp_cost.py: every engine and its cost-changing choices; scripts/dsp_cost_fx.py: the A2 filters, the
inserts, the bus inserts, the send FX) and the runner's (the stock machines: STOCK below). Never edited by hand.
`c_header()` turns it into the ColdFire's tables (dnfw.waverider.coldfire.compose).

The cost of a voice is what one voice-block of it takes on docs/dsp-cost.md's scale (instructions + 4 L2 + 10 DDR):
the dearer of its steady and its note block, plus PER_VOICE (its guard and quiet test, outside the voice), times
1 + MARGIN (knobs other than the defaults, the model's estimate against the unit). The check (csrc) adds, for the
kit: each track's voices x (engine + filter + its inserts), the send FX and the bus inserts, against AVAIL.
"""

from __future__ import annotations

import json
import pathlib

TABLE = pathlib.Path(__file__).with_name("table.json")

MARGIN = 0.15
PER_VOICE = 530                   # the slot loop's guard ~330 + mnm_ages' quiet test ~200 a voice (runner, docs/dsp-cost.md)
OURS = 310_000                    # what our voices, inserts and FX get of the 666,667-cycle frame (the brief; guard LIMIT less the stock's tail)
FIXED = 2_317 + 953 + 8_115       # PERC's entry, the slot loop and smp's loop with no voice (runner, host cut, 2026-11-12)
AVAIL = OURS - FIXED
VOICES = 16
TAIL = 8000 // 16                 # the DSP's per-slot cost telemetry (cycles / 16) over which a released voice still sounds
                                  # (link.c TLM_SOUNDING: idle 1,300..1,500, a held note 16,000..28,000, a release 2,300..3,300)
# the stock machines a voice (runner, scripts/sharc_cost.py --steps stock, 2026-11-12: the whole block with the track on
# the machine less on MIDI), by machine type
STOCK = {0: 14_626, 1: 9_980, 2: 10_998, 3: 5_228, 4: 0}
STOCK_NAMES = {0: "FM TONE", 1: "WAVETONE", 2: "FM DRUM", 3: "SWARMER", 4: "MIDI"}


def per_voice(row: dict) -> int:
    """a dsp_cost.py row -> the table's cost of one voice"""
    return round((max(row["steady"]["cost"], row["trig"]["cost"]) + PER_VOICE) * (1 + MARGIN))


def load() -> dict:
    return json.loads(TABLE.read_text())


def c_header(t: dict | None = None) -> str:
    """the ColdFire's tables, u16 cycles (every cost < 65,536): load_md[TYPE], load_mnm[MNM machine] (its defaults),
    the choice tables by choice index (PLAITS MODL, SOPHIE MODL, ANALOG 2 FLT2, MONOMACHINE ENGN), the sample
    machines and stock machines by machine type, the filters by filter type, the inserts by insert type (a voice),
    the bus inserts and the send FX (an instance)"""
    t = t or load()

    def arr(name: str, vals) -> str:
        vals = list(vals)
        assert all(0 <= v < 65536 for v in vals), name
        return f"static const unsigned short {name}[{len(vals)}] = {{{', '.join(map(str, vals))}}};"

    def by_type(d: dict, n: int = 32) -> list[int]:
        return [d.get(str(k), d.get(k, 0)) for k in range(n)]
    from ..inserts import design as ID
    from ..mnm import machines as MM
    from ..perc import machines as PMx
    from ..waverider import pages as PG
    names = [M.NAME for M in MM.CF_ALL]

    def mi(name: str) -> int:
        return names.index(name) if name in names else -1

    def j(name: str, ctl: str) -> int:
        """the control's index in the ColdFire's 24 (pages.mnm_pnames: page 1's eight, page 2's, page 3's)"""
        return PG.mnm_pnames(MM.CF_ALL[mi(name)]).index(ctl) if mi(name) >= 0 else 0
    assert PMx.TYPE_REC[1] < 256
    lines = ["/* GENERATED by scripts/gen_load_table.py (dnfw.load): the kit load check's costs, cycles a block */",
             f"#define LOAD_AVAIL {t['avail']}u",
             f"#define LOAD_VOICES {VOICES}",
             f"#define LOAD_TAIL {TAIL}u                 /* a released voice still sounding: the DSP's slot cost / 16 over this */",
             f"#define LOAD_MD_N {len(t['md'])}",
             f"#define LOAD_TYPE_SLOT {PMx.TYPE_REC[1]}   /* MACHINEDRUM's TYPE: its frame slot (0..127, x N >> 7) */",
             f"#define LOAD_MI_PLAITS {mi('PLAITS')}",
             f"#define LOAD_MI_SOPHIE {mi('SOPHIE')}",
             f"#define LOAD_MI_A2 {mi('ANALOG2')}",
             f"#define LOAD_J_PLAITS {j('PLAITS', 'MODL')}",
             f"#define LOAD_J_SOPHIE {j('SOPHIE', 'MODL')}",
             f"#define LOAD_J_A2 {j('ANALOG2', 'FLT2')}",
             f"#define LOAD_BUS_MASK {sum(1 << b for b in ID.BUS)}u   /* insert types run once a bus, not a voice */",
             arr("load_md", t["md"]),
             arr("load_mnm", t["mnm"]),
             arr("load_plaits", t["plaits"]),
             arr("load_sophie", t["sophie"]),
             arr("load_a2flt", t["a2flt"]),
             arr("load_mono", t["mono"]),
             arr("load_type", by_type(t["type"])),
             arr("load_filter", by_type(t["filter"], 16)),
             arr("load_ins", by_type(t["ins"], 16)),
             arr("load_bus", by_type(t["bus"], 16)),
             f"#define LOAD_SEND_FDN8 {t['send']['FDN8']}u",
             f"#define LOAD_SEND_XDLY {t['send']['XDLY']}u",
             f"#define LOAD_SEND_JUNO {t['send']['JUNO']}u"]
    return "\n".join(lines) + "\n"
