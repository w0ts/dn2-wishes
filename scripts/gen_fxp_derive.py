"""csrc/fxpage/fxp_derive.h from dnfw.xdly.design and dnfw.fdn8.design: the ColdFire's side of the second pages'
formulas, so that the DSP gets the same float32 words dnfw.*.design.derive gives (docs/fxpage.md).

    python scripts/gen_fxp_derive.py [--check]
"""
from __future__ import annotations

import pathlib
import struct
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from dnfw.fdn8 import design as FD  # noqa: E402
from dnfw.xdly import design as XD  # noqa: E402

OUT = ROOT / "csrc" / "fxpage" / "fxp_derive.h"


def hexf(x) -> str:
    return float(np.float32(x)).hex() + "f"


def bits(x) -> int:
    return struct.unpack("<I", struct.pack("<f", float(np.float32(x))))[0]


def text() -> str:
    kf = [bits(XD.derive(k, XD.KN_DEF, XD.WD_DEF, XD.IN_DEF)[0]) for k in range(128)]
    rows = ["    " + ", ".join(f"0x{v:08X}u" for v in kf[i:i + 6]) + "," for i in range(0, 128, 6)]
    return f"""/* GENERATED by scripts/gen_fxp_derive.py from dnfw.xdly.design and dnfw.fdn8.design; do not edit by hand (test/test_fxpage.py holds it to
 * the design: every knob of every parameter gives the same float32 bits). The Delay page's second page: the knobs
 * (0..127) -> the engine's values the DSP reads (design.EX). */
static const u32 xd_kf_bits[128] = {{
{chr(10).join(rows)}
}};
#define XD_KNEE_F    {hexf(XD.KNEE)}
#define XD_KN_STEP_F {hexf(XD.KN_STEP)}
#define XD_KN_LO_F   {hexf(XD.KN_LO)}
#define XD_WD_K_F    {hexf(XD.WD_K)}
#define XD_IN_K_F    {hexf(XD.IN_K)}
#define XD_SL_DEF {XD.SL_DEF}
#define XD_KN_DEF {XD.KN_DEF}
#define XD_WD_DEF {XD.WD_DEF}
#define XD_IN_DEF {XD.IN_DEF}
#define FD_DF_K_F {hexf(FD.DF_K)}
#define FD_WD_K_F {hexf(FD.WD_K)}
#define FD_FZ_K_F {hexf(FD.FZ_K)}
#define FD_DF_DEF {FD.DF_DEF}
#define FD_WD_DEF {FD.WD_DEF}
#define FD_FZ_DEF {FD.FZ_DEF}
"""


if __name__ == "__main__":
    t = text()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == t else 1)
    OUT.write_text(t)
