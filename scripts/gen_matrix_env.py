"""The matrix's envelope tables (csrc/matrix/env_table.h, docs/matrix.md): stock 1.12's AMP envelope as measured in
Elektron's own DSP code (csrc/matrix/amp_env.json, the SHARC runner), knob by knob, for the ColdFire clone that ENV1
and ENV2 run once a frame (one DSP block, 32 samples).

    python3 scripts/gen_matrix_env.py            # writes csrc/matrix/env_table.h
    python3 scripts/gen_matrix_env.py --check    # exit 1 when the committed table differs

ENV_ATK_S[k]    the attack's step a sample, 1.31 (the clone steps 32 a block, and counts the samples to full scale in
                the block it gets there); knobs whose attack the runner saw end inside one block: their measured length
                (amp_env.json "atk_fast"); 0x7fffffff: full scale at once (knob 0), the whole block in the next stage
ENV_DEC[k]      the decay's ratio a block, 1.31 (knob 127: 0x7fffffff, it does not fall)
ENV_DEC_S[k]    ... a sample: the 32nd root (the rest of the block after the attack ends inside it)
ENV_REL[k]      the release's ratio a block, 1.31 (the decay's table while the release is not measured)
ENV_HOLD[k]     AHD's hold in samples from full scale; 0xffffffff: until the note-off (127, and the knobs not measured)
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "csrc" / "matrix" / "amp_env.json"
OUT = ROOT / "csrc" / "matrix" / "env_table.h"
FULL = 0x7FFFFFFF
GATE = 0xFFFFFFFF


def fixed(x: float) -> int:
    return max(0, min(FULL, round(x * 2 ** 31)))


def table() -> dict[str, list[int]]:
    d = json.loads(DATA.read_text())
    fast = d.get("atk_fast", {}).get("samples", {})
    atk = [(FULL if not fast[str(k)] else fixed(1.0 / fast[str(k)])) if s is None and str(k) in fast
           else FULL if s is None else fixed(s) for k, s in enumerate(d["atk_step"]["per_sample"])]
    dec = [fixed(r) for r in d["dec_ratio"]["per_block"]]
    dec_s = [fixed(r ** (1.0 / 32)) for r in d["dec_ratio"]["per_block"]]
    rel = [fixed(r) for r in (d["rel_ratio"]["per_block"] or d["dec_ratio"]["per_block"])]
    hb = d["hold_blocks"]["samples"]
    hold = [GATE if hb.get(str(k)) is None else int(hb[str(k)]) for k in range(128)]
    return {"ENV_ATK_S": atk, "ENV_DEC": dec, "ENV_DEC_S": dec_s, "ENV_REL": rel, "ENV_HOLD": hold}


def text() -> str:
    def rows(xs):                       # decimal: no word reads as an address to the integration's check
        return "\n".join("    " + ", ".join(f"{x}u" for x in xs[k:k + 8]) + "," for k in range(0, 128, 8))
    out = ["/* Generated by scripts/gen_matrix_env.py from csrc/matrix/amp_env.json (stock 1.12's AMP envelope measured in",
           " * the SHARC runner): do not edit. A knob 0..127 -> the attack's step a sample, the decay's ratio a block and a",
           " * sample, the release's a block (1.31), AHD's hold in samples (0xffffffff: until the note-off). */"]
    for name, xs in table().items():
        out.append(f"static const u32 {name}[128] = {{\n{rows(xs)}\n}};")
    return "\n".join(out) + "\n"


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    if a.check:
        same = OUT.exists() and OUT.read_text() == text()
        print("env_table.h current" if same else "env_table.h differs: run scripts/gen_matrix_env.py")
        return 0 if same else 1
    OUT.write_text(text())
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
