def records(img: bytes):
    def cstr(va: int) -> str:
        o = va - LOAD
        return img[o:img.index(b"\0", o)].decode("latin1") if 0 <= o < len(img) else "?"
    for rid in range(400):
        w = struct.unpack_from(">15I", img, RECORDS + STRIDE * rid - LOAD)
        if not 0x40000000 < w[10] < 0x40400000:
            break
        short = cstr(w[12])
        if short != "ERR":
            yield rid, w[0], short, cstr(w[10]), w[2] >> 8, w[3] >> 8, w[13]


def measured_sections() -> list[str]:
    out = []
    for name, q in MU.stock_measured().items():
        v = q["values"]
        out += [f"### {name} (records {', '.join(map(str, q['records']))}): {q['unit']}", "", q["what"] + ".", "",
                "How: " + q["how"], "", "| knob | " + " | ".join(str(k) for k in range(0, 128, 8)) + " | 127 |",
                "|---" * 18 + "|",
                "| value | " + " | ".join("INF" if v[k] is None else f"{v[k]:g}" for k in list(range(0, 128, 8)) + [127])
                + " |", "", "Every knob is in `src/dnfw/engines/stock_measured.json`; the page reads that knob's own value.", ""]
    return out


def main() -> int:
    img = pathlib.Path(sys.argv[1]).read_bytes()
    tables = MU._stock_table_rows()[0]
    rows = []
    for rid, g, short, long_, lo, hi, fmt in records(img):
        if rid in tables:
            new, how = "exact a knob", "measured: SHARC runner (section above)"
        elif rid in MU.STOCK_UNITS:
            kind, fn = MU.STOCK_UNITS[rid][:2]
            if kind == "pct":
                new, how = "0..100 %", "phase 1: % of the range (a plain amount; not a measured unit)"
            else:
                new, how = f"{kind} (curve)", "measured: SHARC runner, a fitted law (section above)"
        elif rid in MEASURE:
            new, how = f"(phase 2) {MEASURE[rid]}", "to measure: SHARC runner, else on the unit"
        elif rid in KEEP:
            new, how = "stock's", "kept: " + KEEP[rid]
        elif fmt == PLAIN and g in (24, 25):
            new, how = "stock's", "kept: MIDI CC value / number"
        elif fmt == PLAIN:
            new, how = "stock's", "not classified yet"
        else:
            new, how = "stock's", "stock's own text (not a plain number)"
        rows.append(f"| {rid} | {GROUPS.get(g, g)} | {short} | {long_} | {lo}..{hi} | `{fmt:#x}` | {new} | {how} |")
    head = DOC.read_text().split(MARK)[0]
    body = ["## Measured", ""] + measured_sections() + ["## Every record", "",
            "| rec | page | knob | long name | range | stock formatter | new text | how |",
            "|---|---|---|---|---|---|---|---|"] + rows
    DOC.write_text(head + MARK + "\n\n" + "\n".join(body) + "\n")
    return 0


