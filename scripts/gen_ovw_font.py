"""The inserts overview's 3x5 letters (csrc/inserts/ovw_font.h) from the project's 3x5 font.

    python scripts/gen_ovw_font.py

Each glyph is 15 bits, row 0 (top) first, bit 14 = row 0's left pixel. Only the characters the overview draws.
test/test_ins_overview.py holds the header to src/dnfw/font3x5.json.
"""

import pathlib

from dnfw.inserts import overview

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "csrc/inserts/ovw_font.h"


def main() -> None:
    lines = ["/* Generated by scripts/gen_ovw_font.py from src/dnfw/font3x5.json -- do not edit by hand.",
             " * The inserts overview's letters: OVW_CHARS[i] drawn from OVW_GLYPH[i], 15 bits, row 0 (top) first,",
             " * bit 14 = row 0's left pixel. */",
             f'static const char OVW_CHARS[] = "{overview.CHARS}";',
             "static const unsigned short OVW_GLYPH[] = {"]
    words = [f"0x{overview.glyph_bits(ch):04x}" for ch in overview.CHARS]
    for k in range(0, len(words), 10):
        lines.append("    " + ", ".join(words[k:k + 10]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(words)} glyphs")


if __name__ == "__main__":
    main()
